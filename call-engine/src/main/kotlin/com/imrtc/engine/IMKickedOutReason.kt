package com.imrtc.engine

/**
 * 被踢下线的原因。
 *
 * **不合并成一个「被踢」**：这两种情况宿主的处置完全相反——一个该回登录页，
 * 一个该悄悄换票重来。合并的结果是宿主只能都当登录失效处理，
 * 把本可静默恢复的场景也变成了「请重新登录」。
 *
 * 用 `enum class` 而不是字符串：Java 侧可用、类型安全，
 * 且 CONVENTIONS §4 明确允许枚举出现在公开面。
 */
enum class IMKickedOutReason {
    /**
     * 同账号同设备号在别处登录，或宿主主动吊销（`POST /v1/sessions/revoke`）。
     *
     * 两者在线路上都是 `4403` / `1104`，**客户端无从区分**。
     * 宿主该做的是**回登录页**——换票救不了被封的账号。
     */
    TAKEN_OVER,

    /**
     * 票不被接受，且连续三次都没换上（`4401` 用尽）。
     *
     * 宿主该做的是**重新取一枚票再 login**，不必打扰用户。
     */
    AUTH_EXPIRED,

    /**
     * 服务端拒绝了这次接入的**参数**：`device_id` 不合规、`protocol_version` 不受支持、
     * 应用被停用之类（握手应答里 `retryable=false` 的那些错误码）。
     *
     * **与 [AUTH_EXPIRED] 的区别是「换票救不救得了」**：票过期换一张就好，
     * 而 `device_id` 里有个空格这件事，重连一万次它还是有空格。
     * 所以这一类**一次就放弃**，不像 4401 那样给三次机会——重试不会让参数变对，
     * 只会让日志里刷满同一条错误，把真正的原因埋掉。
     *
     * 宿主该做的是**去改配置**，不是换票、也不是让用户重试。
     * 具体哪里不对看同时抛出的 [IMCallEngineListener.onError] 的 code 与 message。
     */
    CONFIG_REJECTED,
}
